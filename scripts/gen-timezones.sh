#!/bin/sh
# Make crates/loma-editor/src/timezones_data.rs from the time zone database's
# zone.tab: every zone with one representative place (public domain, from
# https://www.iana.org/time-zones). Loma suggests the zone nearest a garden.
#
#   scripts/gen-timezones.sh [path/to/zone.tab]
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
TAB="${1:-/usr/share/zoneinfo/zone.tab}"
VERSION=$(cat "$(dirname "$TAB")/+VERSION" 2>/dev/null || echo unknown)
OUT="$ROOT/crates/loma-editor/src/timezones_data.rs"
{
  echo "// Generated by scripts/gen-timezones.sh from the time zone database's"
  echo "// zone.tab (version $VERSION; public domain). Don't edit by hand."
  echo ""
  echo "/// Every zone with one representative place: (name, latitude, longitude)."
  echo "pub(crate) const ZONES: &[(&str, f64, f64)] = &["
  grep -v '^#' "$TAB" | awk -F'\t' '
    # ISO 6709: +DDMM[SS]+DDDMM[SS]
    function deg(s, w,   sign, d, m, sec) {
      sign = substr(s, 1, 1) == "-" ? -1 : 1
      d = substr(s, 2, w); m = substr(s, 2 + w, 2)
      sec = length(s) > 3 + w ? substr(s, 4 + w, 2) : 0
      return sign * (d + m / 60 + sec / 3600)
    }
    NF >= 3 {
      c = $2
      split_at = match(substr(c, 2), /[+-]/) + 1
      lat = substr(c, 1, split_at - 1); lon = substr(c, split_at)
      printf "    (\"%s\", %.4f, %.4f),\n", $3, deg(lat, 2), deg(lon, 3)
    }' | LC_ALL=C sort
  echo "];"
} > "$OUT"
echo "gen-timezones: wrote $(grep -c '^    ("' "$OUT") zones to $OUT"
